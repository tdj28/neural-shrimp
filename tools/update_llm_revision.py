"""Refresh the big paper's revision timestamp on source saves, never on builds.

python3 tools/update_llm_revision.py [--watch]
Only .tex/.bib sources and figure assets count; generated TeX/PDF build outputs
and revision-date.tex itself are excluded. The generated file travels with the
manuscript so plain pdflatex and source archives do not require Python.
"""
import argparse
from datetime import datetime
from pathlib import Path
import tempfile
import time
from zoneinfo import ZoneInfo

DEFAULT_ROOT = Path(__file__).resolve().parents[1] / "paper" / "llm"
FIGURE_SUFFIXES = {".pdf", ".png", ".jpg", ".jpeg", ".svg", ".eps", ".tex"}


def source_signature(root):
    files = {
        p for p in root.rglob("*")
        if p.is_file() and p.name != "revision-date.tex"
        and (p.suffix in {".tex", ".bib"}
             or (root / "figures" in p.parents and p.suffix.lower() in FIGURE_SUFFIXES))
    }
    return tuple(sorted((str(p.relative_to(root)), p.stat().st_mtime_ns,
                         p.stat().st_size) for p in files))


def update(root, signature=None):
    signature = source_signature(root) if signature is None else signature
    if not signature:
        raise RuntimeError(f"No manuscript sources found in {root}")
    latest = max(row[1] for row in signature)
    dt = datetime.fromtimestamp(latest / 1e9, ZoneInfo("America/Los_Angeles"))
    stamp = f"{dt:%B} {dt.day}, {dt:%Y at %H:%M:%S %Z}"
    text = ("% Generated by tools/update_llm_revision.py from the latest source save.\n"
            "% Do not edit; the original date is fixed in main.tex.\n"
            f"\\newcommand{{\\revisiondate}}{{{stamp}}}\n")
    dest = root / "revision-date.tex"
    if dest.exists() and dest.read_text() == text:
        return False
    # The watcher and a build hook may run at the same time.
    with tempfile.NamedTemporaryFile(mode="w", dir=root, prefix=".revision-",
                                     suffix=".tmp", delete=False) as handle:
        handle.write(text)
        temporary = Path(handle.name)
    temporary.replace(dest)
    print(stamp, flush=True)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--watch", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    previous = None
    while True:
        signature = source_signature(root)
        if signature != previous:
            update(root, signature)
            previous = signature
        if not args.watch:
            return
        time.sleep(1)


if __name__ == "__main__":
    main()
