"""Write docs/hardware-ledger.md: which hardware produced which exploratory result.

Scans every explore output's metadata.json under DATA/explore for the CUDA
backend record (device name, compute capability, driver, CUDA build, library
hash) and labels runs without one as CPU runs. Host CPU and software versions
are taken from the current machine and environment; frozen experiments carry
their own receipts and are listed with their recorded platform.
"""

import json
import os
import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = Path(os.environ.get("NEURAL_SHRIMP_DATA", ROOT.parent / "neural-shrimp-data"))
OUT = ROOT / "docs" / "hardware-ledger.md"


def cpu_model():
    for line in Path("/proc/cpuinfo").read_text().splitlines():
        if line.startswith("model name"):
            return line.split(":", 1)[1].strip()
    return platform.processor()


def versions():
    out = {"python": platform.python_version()}
    for name in ("numpy", "scipy", "torch"):
        try:
            out[name] = __import__(name).__version__
        except ImportError:
            out[name] = "not installed"
    return out


def gpu_rows():
    rows = []
    for meta in sorted((DATA / "explore").rglob("metadata.json")):
        try:
            record = json.loads(meta.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        backend = record.get("backend") or {}
        device = backend.get("device") or {}
        rel = meta.parent.relative_to(DATA / "explore")
        if device:
            rows.append((str(rel), "GPU", f"{device.get('name')} (sm_{device.get('major')}{device.get('minor')}, "
                         f"{int(device.get('total_bytes', 0)) // 2**20} MiB)",
                         f"driver {backend.get('nvidia_driver')}; {backend.get('nvcc_version') or ''}".strip(),
                         (backend.get("library_sha256") or "")[:12]))
        else:
            rows.append((str(rel), "CPU", cpu_model(), "", ""))
    return rows


def main():
    head = subprocess.run(["git", "rev-parse", "--short=12", "HEAD"], cwd=ROOT, capture_output=True,
                          text=True).stdout.strip()
    v = versions()
    lines = [
        "# Hardware ledger",
        "",
        "Which hardware produced which result, so the work can be recreated on",
        f"similar machines. Generated by `tools/hardware_ledger.py` at commit `{head}`;",
        "regenerate after new runs.",
        "",
        "## Machines",
        "",
        f"- **Local host (`zeta`):** {cpu_model()}, {os.cpu_count()} hardware threads; Linux.",
        "- **Local GPU:** NVIDIA RTX 2000 Ada Generation, 16 GB, compute capability 8.9",
        "  (sm_89), driver 580.178.04 (CUDA driver API 13.0). Float64 throughput is about",
        "  1/64 of float32 on this card.",
        "- **CUDA engine build:** `native/gdmap_cuda.cu` compiled with nvcc 12.4",
        "  (`-O3 -std=c++17 -arch=sm_89 --fmad=false --ftz=false --prec-div=true",
        "  --prec-sqrt=true`, host compiler g++-12), library SHA-256 prefix `062c5084efa7`;",
        "  build receipt beside the library in the data store. The backend refuses other",
        "  compute capabilities until qualified on them.",
        f"- **Software (current environment, from `uv.lock`):** Python {v['python']}, numpy {v['numpy']},",
        f"  scipy {v['scipy']}, torch {v['torch']} (torch is used only for GPU-side",
        "  bookkeeping in the rotation-map driver and for real-data experiments).",
        "- **Rented GPUs (RunPod):**",
        "  - Phase 0, 8 October 2026, pod v7jkobowrc6n4t: NVIDIA H100 NVL (95,830 MiB,",
        "    compute capability 9.0, driver 570.133.20), image",
        "    runpod/pytorch:2.4.0-py3.11-cuda12.4.1-devel-ubuntu22.04; engine built there",
        "    with nvcc 12.4 (V12.4.131), g++-12 12.3.0, `-arch=sm_90`, mirror flags",
        "    (fmad off); Python 3.12.15, numpy 2.5.3, scipy 1.18.1 (uv); torch 2.4.1+cu124",
        "    for the benchmark. Receipts: `../neural-shrimp-data/runpod/phase0/`.",
        "    Outcome: outputs are not bitwise identical to the sm_89 build (differences",
        "    confined to chaotic and sensitive cells; status labels differ in 0.1% of",
        "    S2-28011 cells and 1 of 1,024 S1R cells), see `docs/research-log.md`.",
        "  Each later rented run is to be added here the same way.",
        "",
        "## Frozen experiments",
        "",
        "- **EXP-028** (trainability maps) and **EXP-029** (Track B controls): CPU, float64,",
        "  on the local host; platform details in their receipts under",
        "  `../neural-shrimp-data/raw/` and audits under `../neural-shrimp-data/audits/`.",
        "",
        "## Exploratory runs with saved metadata",
        "",
        "| Output (under `explore/`) | Device | Hardware | Driver / CUDA build | Library |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| `{r[0]}` | {r[1]} | {r[2]} | {r[3]} | {r[4]} |" for r in gpu_rows()]
    lines += ["", "Exploratory outputs without a metadata file (for example the agent streams'",
              "CPU runs) ran on the local host CPU unless their stream summary says otherwise;",
              "each run card in `docs/research-log.md` records its command and commit.", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} with {len(lines)} lines")


if __name__ == "__main__":
    sys.exit(main())
