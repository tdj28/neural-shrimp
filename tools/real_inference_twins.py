SKETCH = 32
REMERGE = 50          # identical consecutive tokens after a split that count as a re-merge
LEAD = 50             # re-nudges start this many steps after the first difference
WINDOW = 100          # steps generated by each re-nudge
RENUDGES = 4


# ---------------------------------------------------------------------------------------------------- samplers

def plain_probs(torch, z, temps):
    """Full softmax at temperature T (rows)."""
    return torch.softmax(z / temps[:, None], dim=-1)


def qwen_probs(torch, z, temps, seen, penalty=1.1, top_k=20, top_p=0.8):
    """Qwen's default processors in Hugging Face order: repetition penalty over every token already in the context
    (prompt included), temperature, top-k, top-p. Returns a full-vocabulary distribution with at most top_k
    nonzero entries."""
    z = torch.where(seen, torch.where(z < 0, z * penalty, z / penalty), z) / temps[:, None]
    vals, idx = torch.topk(z, top_k, dim=-1)                  # sorted, largest first
    p = torch.softmax(vals, dim=-1)
    cum = torch.cumsum(p, dim=-1)
    keep = (cum - p) < top_p                                   # the smallest prefix whose mass reaches top_p
    keep[:, 0] = True
    p = torch.where(keep, p, torch.zeros_like(p))
    p = p / p.sum(dim=-1, keepdim=True)
    out = torch.zeros_like(z)
    out.scatter_(1, idx, p)
    return out


def inverse_cdf(torch, q, u):
    """Token per row where the uniform u (rows) falls in the cumulative distribution (vocabulary order)."""
    cdf = torch.cumsum(q, dim=-1)
    tok = torch.searchsorted(cdf, (u * cdf[:, -1]).contiguous()[:, None]).squeeze(1)
    return torch.clamp(tok, max=q.shape[1] - 1)


def entropy(torch, q):
    lq = torch.where(q > 0, torch.log(q), torch.zeros_like(q))
    return -(q * lq).sum(-1)


# ------------------------------------------------------------------------------------------------------- model

def check_float64(model):
    """The float64 patches of keep_float64_norms are in place (as c12_hidden_readouts.check_float64)."""
    import torch
    dtypes = sorted({str(p.dtype) for p in model.parameters()})
    norms = {type(m).__name__: type(m).forward.__qualname__ for m in model.modules()
             if type(m).__name__.endswith("RMSNorm")}
    rotary = [hasattr(m, "_inv_freq64") and type(m).forward.__qualname__.startswith("keep_float64_norms")
              for m in model.modules() if type(m).__name__.endswith("RotaryEmbedding")]
    ok = (dtypes == [str(torch.float64)] and norms and all(q.startswith("keep_float64_norms") for q in norms.values())
          and rotary and all(rotary))
    res = {"param_dtypes": dtypes, "rmsnorm_forward": norms, "rotary_float64": rotary,
           "attn_implementation": getattr(model.config, "_attn_implementation", None), "ok": bool(ok)}
    if not ok:
        raise SystemExit(f"float64 patches missing: {res}")
    return res


class Generator:
    def __init__(self, threads, device):
        import explore_llm_attractors as ela
        import explore_llm_phase_map as elpm

        self.ela, self.elpm = ela, elpm
        self.sm = elpm.SteeredModel("qwen0.5b", 12, threads, "float64", device, "native")
        self.torch = self.sm.torch
        self.model, self.tok, self.device = self.sm.model, self.sm.tok, self.sm.device
        self.f64 = check_float64(self.model)
        self._last = {}
        self.model.model.norm.register_forward_hook(lambda m, i, o: self._last.__setitem__("h", o[:, -1, :]))
        self.emb = self.model.get_input_embeddings()
        self.V = self.emb.weight.shape[0]
        self.d = self.emb.weight.shape[1]
        self.R = self.torch.as_tensor(np.random.default_rng(777).normal(size=(self.d, SKETCH)) / np.sqrt(self.d),
                                      dtype=self.torch.float64, device=self.device)
        self.v = elpm.load_vectors("llm-phase-map/vectors-l12")["philosophy"]

    def prompt_ids(self, prompt):
        if isinstance(prompt, dict):                            # chat messages of a prompt variant
            messages = prompt["messages"]
        else:
            messages = [{"role": "system", "content": self.ela.PROMPTS[prompt]},
                        {"role": "user", "content": self.ela.OPENER}]
        text = self.tok.apply_chat_template(messages, add_generation_prompt=True, tokenize=False)
        ids = self.tok(text, add_special_tokens=False)["input_ids"]
        if isinstance(prompt, dict) and prompt.get("prefix_token_ids") and prompt["prefix_token_ids"] != ids:
            raise SystemExit("prompt variant ids differ from its recorded prefix_token_ids")
        return ids

    def generate(self, ctx, nudges, steer, temps, sampler, uniforms, steps, out_hidden=True):
        """ctx: list of token-id lists (rows, may differ in length; left-padded); nudges (rows, d) added to each
        row's first real token embedding; steer (rows, d); temps (rows,); uniforms (rows, steps). Returns tokens
        (rows, steps), the distributions' TV/KL to the row's partner are computed by the caller from the returned
        per-step log-probabilities, so this returns q-based summaries for pairs (row 2k, 2k+1)."""
        from transformers import DynamicCache

        torch = self.torch
        B = len(ctx)
        L = max(len(c) for c in ctx)
        ids = torch.zeros((B, L), dtype=torch.long, device=self.device)
        mask = torch.zeros((B, L), dtype=torch.long, device=self.device)
        seen = torch.zeros((B, self.V), dtype=torch.bool, device=self.device)
        for r, c in enumerate(ctx):
            ids[r, L - len(c):] = torch.as_tensor(c, device=self.device)
            mask[r, L - len(c):] = 1
            seen[r, torch.as_tensor(sorted(set(c)), device=self.device)] = True
        with torch.no_grad():
            x = self.emb(ids)
            first = L - torch.as_tensor([len(c) for c in ctx], device=self.device)
            x[torch.arange(B, device=self.device), first] += torch.as_tensor(nudges, dtype=x.dtype, device=self.device)
            x = x * mask[..., None]
            pos = torch.clamp(torch.cumsum(mask, 1) - 1, min=0)
            T = torch.as_tensor(temps, dtype=torch.float64, device=self.device)
            U = torch.as_tensor(uniforms, dtype=torch.float64, device=self.device)
            self.sm.steer = torch.as_tensor(np.asarray(steer), dtype=torch.float64, device=self.device)[:, None, :]
            cache = DynamicCache()
            toks = np.zeros((B, steps), dtype=np.int64)
            ent = np.zeros((B, steps))
            tv = np.zeros((B // 2, steps))
            kl = np.full((B // 2, steps), np.nan)
            sk = np.zeros((B, steps, SKETCH), dtype=np.float32)
            try:
                o = self.model(inputs_embeds=x, attention_mask=mask, position_ids=pos, past_key_values=cache,
                               use_cache=True, logits_to_keep=1)
                for t in range(steps):
                    z = o.logits[:, -1, :].to(torch.float64)
                    if out_hidden:
                        sk[:, t] = (self._last["h"].to(torch.float64) @ self.R).cpu().numpy()
                    q = plain_probs(torch, z, T) if sampler == "plain" else qwen_probs(torch, z, T, seen)
                    a, b = q[0::2], q[1::2]
                    tv[:, t] = (0.5 * (a - b).abs().sum(-1)).cpu().numpy()
                    if sampler == "plain":
                        la = torch.log_softmax(z[0::2] / T[0::2, None], -1)
                        lb = torch.log_softmax(z[1::2] / T[1::2, None], -1)
                        kl[:, t] = (a * (la - lb)).sum(-1).cpu().numpy()
                    ent[:, t] = entropy(torch, q).cpu().numpy()
                    nxt = inverse_cdf(torch, q, U[:, t])
                    toks[:, t] = nxt.cpu().numpy()
                    seen[torch.arange(B, device=self.device), nxt] = True
                    mask = torch.cat([mask, torch.ones((B, 1), dtype=mask.dtype, device=self.device)], 1)
                    pos = pos[:, -1:] + 1
                    if t + 1 < steps:
                        o = self.model(input_ids=nxt[:, None], attention_mask=mask, position_ids=pos,
                                       past_key_values=cache, use_cache=True, logits_to_keep=1)
            finally:
                self.sm.steer = None
        return toks, tv, kl, ent, sk


def unit_nudges(rng, n, d):
    g = rng.normal(size=(n, d))
    return g / np.linalg.norm(g, axis=1, keepdims=True)


def first_difference(a, b):
    diff = np.nonzero(a != b)[0]
    return int(diff[0]) if len(diff) else -1


def remerged(a, b, start, need=REMERGE):
    run = 0
    for t in range(start, len(a)):
        run = run + 1 if a[t] == b[t] else 0
        if run >= need:
            return True
    return False


def run(args):
    global LEAD, WINDOW                    # smaller values only for smoke tests; RI1 uses the defaults
    LEAD, WINDOW = args.lead, args.window
    cells = json.loads((ROOT / args.cells).read_text())
    gen = Generator(args.threads, args.device)
    torch = gen.torch
    from explore_llm_attractors import DATA
    out = DATA / "explore" / args.out
    out.mkdir(parents=True, exist_ok=True)
    e0n = None
    S, N = args.seeds, args.tokens
    uniforms = np.random.default_rng(20261021).random((S, N + WINDOW))
    tasks = [(c, s) for c in cells for s in args.samplers]
    meta = {"lead": LEAD, "window": WINDOW, "cells": args.cells, "cells_sha256": hashlib.sha256((ROOT / args.cells).read_bytes()).hexdigest(),
            "seeds": S, "tokens": N, "samplers": args.samplers, "float64": gen.f64, "tasks": []}
    tic = time.perf_counter()
    groups = {}
    for c, s in tasks:                                     # batch tasks with the same prompt and sampler
        key = (json.dumps(c.get("prompt", "open"), sort_keys=True), s)
        groups.setdefault(key, []).append(c)
    for (pkey, sampler), group in groups.items():
        prompt = json.loads(pkey)
        ids = gen.prompt_ids(prompt)
        with torch.no_grad():
            e0 = gen.emb(torch.as_tensor([ids[0]], device=gen.device))[0].to(torch.float64).cpu().numpy()
        e0n = float(np.linalg.norm(e0))
        for g0 in range(0, len(group), args.tasks_per_batch):
            part = group[g0:g0 + args.tasks_per_batch]
            ctx, nud, steer, temps, uni, rows = [], [], [], [], [], []
            for c in part:
                rng = np.random.default_rng(int(hashlib.sha256(c["name"].encode()).hexdigest()[:8], 16))
                dirs = unit_nudges(rng, S, gen.d)
                eps = float(c.get("nudge", 1e-8))
                for k in range(S):
                    for copy in (0, 1):
                        ctx.append(ids)
                        nud.append(dirs[k] * eps * e0n * copy)
                        steer.append(c["alpha"] * gen.v)
                        temps.append(10.0 ** c["log_t"])
                        uni.append(uniforms[k, :N])
                        rows.append((c["name"], k, copy))
            toks, tv, kl, ent, sk = gen.generate(ctx, np.array(nud), np.array(steer), np.array(temps), sampler,
                                                 np.array(uni), N)
            # re-nudges for pairs that split and did not re-merge, with room for a full window
            rctx, rnud, rsteer, rtemps, runi, rrows = [], [], [], [], [], []
            for j, c in enumerate(part):
                rng = np.random.default_rng(int(hashlib.sha256((c["name"] + sampler + "renudge").encode())
                                                .hexdigest()[:8], 16))
                for k in range(S):
                    p = (j * S + k)
                    a, b = toks[2 * p], toks[2 * p + 1]
                    fd = first_difference(a, b)
                    if fd < 0 or remerged(a, b, fd) or fd + LEAD + WINDOW > N:
                        continue
                    s0 = fd + LEAD
                    base_nudge = np.array(nud[2 * p + 1])
                    for copy, seq in ((0, a), (1, b)):
                        for r in range(RENUDGES + 1):
                            fresh = unit_nudges(rng, 1, gen.d)[0] * 1e-8 * e0n if r < RENUDGES else 0.0
                            rctx.append(list(ids) + [int(t) for t in seq[:s0]])
                            rnud.append((base_nudge if copy else 0.0) + fresh)
                            rsteer.append(c["alpha"] * gen.v)
                            rtemps.append(10.0 ** c["log_t"])
                            runi.append(uniforms[k, s0:s0 + WINDOW])
                            rrows.append((j, k, copy, r, s0))
            rres = {}
            for r0 in range(0, len(rctx), args.renudge_batch):
                # pairs of rows are not partners here: TV/KL columns are ignored, rows are compared to their parent
                sl = slice(r0, r0 + args.renudge_batch)
                n = len(rctx[sl])
                pad = n % 2
                cx, nu = rctx[sl] + ([rctx[sl][-1]] if pad else []), list(rnud[sl]) + ([rnud[sl][-1]] if pad else [])
                st = list(rsteer[sl]) + ([rsteer[sl][-1]] if pad else [])
                tp = list(rtemps[sl]) + ([rtemps[sl][-1]] if pad else [])
                un = list(runi[sl]) + ([runi[sl][-1]] if pad else [])
                rt, _, _, re_, rs = gen.generate(cx, np.array([np.broadcast_to(x, (gen.d,)) for x in nu]),
                                                 np.array(st), np.array(tp), sampler, np.array(un), WINDOW)
                for i in range(n):
                    rres[r0 + i] = (rt[i], re_[i], rs[i])
            for j, c in enumerate(part):
                sel = [i for i, rr in enumerate(rrows) if rr[0] == j]
                sl = slice(2 * j * S, 2 * (j + 1) * S)
                name = f"{c['name']}--{sampler}"
                path = out / f"{name}.npz"
                np.savez_compressed(
                    path, tokens=toks[sl].reshape(S, 2, N), tv=tv[j * S:(j + 1) * S], kl=kl[j * S:(j + 1) * S],
                    entropy=ent[sl].reshape(S, 2, N), sketch=sk[sl].reshape(S, 2, N, SKETCH),
                    renudge_rows=np.array([rrows[i][1:] for i in sel], dtype=np.int64).reshape(-1, 4),
                    renudge_tokens=np.array([rres[i][0] for i in sel]).reshape(-1, WINDOW),
                    renudge_entropy=np.array([rres[i][1] for i in sel]).reshape(-1, WINDOW),
                    renudge_sketch=np.array([rres[i][2] for i in sel]).reshape(-1, WINDOW, SKETCH))
                meta["tasks"].append({"name": name, "cell": c, "sampler": sampler, "prompt_tokens": len(ids),
                                      "renudge_rows": len(sel), "file": path.name,
                                      "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                                      "seconds": round(time.perf_counter() - tic, 1)})
                print(json.dumps({"task": name, "renudges": len(sel), "seconds": round(time.perf_counter() - tic, 1)}),
                      flush=True)
            with open(out / "progress.jsonl", "a") as h:
                h.write(json.dumps({"done": len(meta["tasks"]), "of": len(tasks),
                                    "seconds": round(time.perf_counter() - tic, 1)}) + "\n")
            (out / "run.json").write_text(json.dumps(meta, indent=1))
    meta["seconds"] = round(time.perf_counter() - tic, 1)
    meta["complete"] = len(meta["tasks"]) == len(tasks)
    (out / "run.json").write_text(json.dumps(meta, indent=1))


# ----------------------------------------------------------------------------------------------------- analysis

def pair_outcome(a, b, tv, rows, rtoks, rsk, sk, N):
    """Outcome of one pair: no_split, remerge, split_stable (every nudged re-nudge of both copies repeats its parent
    over the window), split_scatter (both copies have a diverging re-nudge), split_mixed, unresolved (split too late
    for a full re-nudge window) or invalid (a zero-nudge control re-nudge left its parent: recomputation not exact)."""
    fd = first_difference(a, b)
    upto = N if fd < 0 else fd
    t = np.arange(upto)
    good = tv[:upto] > 1e-14
    slope = np.nan
    if good.sum() >= 8:
        slope = float(np.polyfit(t[good], np.log(tv[:upto][good]), 1)[0])
    res = {"first_diff": fd, "tv_slope": slope, "tv0": float(tv[0]), "tv_max_agree": float(tv[:upto].max()) if upto else float("nan")}
    if fd < 0:
        res["outcome"] = "no_split"
        return res
    if remerged(a, b, fd):
        res["outcome"] = "remerge"
        return res
    if len(rows) == 0:
        res["outcome"] = "unresolved"
        return res
    s0 = int(rows[0][3])
    parents = (a, b)
    hold = {0: [], 1: []}
    for (k, copy, r, s), rt in zip(rows, rtoks):
        same = bool(np.all(rt == parents[copy][s0:s0 + WINDOW]))
        if r == RENUDGES:
            if not same:
                res["outcome"] = "invalid"
                return res
            continue
        hold[copy].append(same)
    stable = [all(hold[c]) for c in (0, 1)]
    if all(stable):
        res["outcome"] = "split_stable"
    elif not any(stable):
        res["outcome"] = "split_scatter"
    else:
        res["outcome"] = "split_mixed"
    m = min(50, WINDOW)
    w = slice(s0 + WINDOW - m, s0 + WINDOW)
    dab = float(np.linalg.norm(sk[0][w] - sk[1][w], axis=1).mean())
    dwithin = [float(np.linalg.norm(rs[-m:] - sk[copy][w], axis=1).mean())
               for (k, copy, r, s), rs in zip(rows, rsk) if r < RENUDGES]
    res.update(d_ab=dab, d_within=float(np.mean(dwithin)))
    return res


def analyze(args):
    from explore_llm_attractors import DATA
    src = DATA / "explore" / args.raw
    meta = json.loads((src / "run.json").read_text())
    N = meta["tokens"]
    global LEAD, WINDOW
    LEAD, WINDOW = meta.get("lead", LEAD), meta.get("window", WINDOW)
    summary = []
    gates = []
    for task in meta["tasks"]:
        z = np.load(src / task["file"])
        ok = bool(np.all(np.isfinite(z["tv"])) and np.all(np.isfinite(z["entropy"])))
        if hashlib.sha256((src / task["file"]).read_bytes()).hexdigest() != task["sha256"]:
            ok = False
        rows, rt, rs = z["renudge_rows"], z["renudge_tokens"], z["renudge_sketch"]
        pairs = []
        for k in range(meta["seeds"]):
            sel = np.nonzero(rows[:, 0] == k)[0] if len(rows) else []
            pairs.append(pair_outcome(z["tokens"][k, 0], z["tokens"][k, 1], z["tv"][k], rows[sel], rt[sel], rs[sel],
                                      z["sketch"][k], N))
        outc = [p["outcome"] for p in pairs]
        fds = np.array([p["first_diff"] if p["first_diff"] >= 0 else N for p in pairs])
        slopes = np.array([p["tv_slope"] for p in pairs], dtype=float)
        c = task["cell"]
        row = {"task": task["name"], "group": c["group"], "position": c.get("position"), "alpha": c["alpha"],
               "log_t": c["log_t"], "prompt": c.get("prompt_name", "open"), "sampler": task["sampler"],
               "nudge": c.get("nudge", 1e-8),
               "soft_lyapunov": c.get("soft_lyapunov"), "soft_period": c.get("soft_period"),
               "soft_entropy": c.get("soft_entropy"),
               "real_entropy": float(z["entropy"].mean()), "split_rate": float(np.mean(fds < N)),
               "median_first_diff": float(np.median(fds)),
               "median_tv_slope": float(np.nanmedian(slopes)) if np.isfinite(slopes).any() else None,
               "counts": {k: outc.count(k) for k in sorted(set(outc))}, "gate_ok": ok}
        gates.append(ok)
        summary.append(row)
    out = ROOT / args.receipt
    out.parent.mkdir(parents=True, exist_ok=True)
    rec = {"raw": args.raw, "run_json_sha256": hashlib.sha256((src / "run.json").read_bytes()).hexdigest(),
           "float64": meta["float64"]["ok"], "complete": meta.get("complete"), "all_gates_ok": all(gates),
           "rows": summary}
    # matched pairs: bootstrap of chaotic minus periodic means
    rng = np.random.default_rng(0)
    for sampler in meta["samplers"]:
      for nudge in sorted({r["nudge"] for r in summary if r["group"] == "matched"}):
        for key in ("split_rate", "median_tv_slope", "median_first_diff"):
            sel = [r for r in summary if r["group"] == "matched" and r["sampler"] == sampler and r["nudge"] == nudge
                   and r[key] is not None]
            ch = [r[key] for r in sel if r["soft_lyapunov"] > 0]
            pe = [r[key] for r in sel if r["soft_lyapunov"] < 0]
            if ch and pe:
                boots = [np.mean(rng.choice(ch, len(ch))) - np.mean(rng.choice(pe, len(pe))) for _ in range(4000)]
                rec.setdefault("matched", {})[f"{sampler}:{nudge:g}:{key}"] = {
                    "chaotic_minus_periodic": float(np.mean(ch) - np.mean(pe)),
                    "ci95": [float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))],
                    "chaotic": ch, "periodic": pe}
    out.write_text(json.dumps(rec, indent=1))
    if args.plot:
        plot_line(summary, ROOT / args.plot)
    print(json.dumps({"receipt": str(out), "all_gates_ok": all(gates), "tasks": len(summary)}))


def plot_line(summary, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    line = [r for r in summary if r["group"] == "line" and r["nudge"] > 0]
    combos = sorted({(r["prompt"], r["sampler"], r["nudge"]) for r in line})
    fig, axes = plt.subplots(4, len(combos), figsize=(3.2 * len(combos), 11), sharex=True, squeeze=False)
    for j, (pr, sa, nu) in enumerate(combos):
        rs = sorted([r for r in line if r["prompt"] == pr and r["sampler"] == sa and r["nudge"] == nu],
                    key=lambda r: r["position"])
        x = [r["position"] for r in rs]
        lam = [r["soft_lyapunov"] for r in rs]
        series = [("split rate (pairs)", [r["split_rate"] for r in rs]),
                  ("median first difference (token)", [r["median_first_diff"] for r in rs]),
                  ("median TV growth per step", [r["median_tv_slope"] for r in rs]),
                  ("entropy (real, nats)", [r["real_entropy"] for r in rs])]
        for i, (lab, y) in enumerate(series):
            ax = axes[i, j]
            ax.plot(x, [np.nan if v is None else v for v in y], "o-", color="k")
