"""Exploratory (run RI1): do the soft map's regimes carry over to real inference?

Real inference here is ordinary token-by-token generation of Qwen2.5-0.5B-Instruct: hard tokens, the full growing
context in a key-value cache, the article's prompt and the philosophy steering vector added at layer 12 (the same
hook and vectors as explore_llm_soft_loop.py), float64 weights with the RMSNorm and rotary patches of
keep_float64_norms (checked at load).

For every setting (alpha, T) and seed, two copies are generated with common random numbers: each step draws one
uniform u per seed and both copies take the token where u falls in their own cumulative distribution (vocabulary
order). Copy B's first prompt-token embedding is nudged by 1e-8 relative in a seeded random direction. Two
samplers: plain temperature sampling (full softmax at T) and Qwen's default processors (repetition penalty 1.1,
temperature, top-k 20, top-p 0.8) at the same T.

Recorded per pair and step: the two tokens, the total-variation and (plain sampler) KL distance between the copies'
next-token distributions, each copy's entropy, and a 32-dimensional sketch of each copy's final hidden state. Pairs
that split and do not re-merge are re-nudged: from step s0 = first difference + 50, each copy restarts from its own
token history with a fresh 1e-8 nudge (four times) or no nudge (one control), with the same uniforms, for 100 steps.

Subcommands
  run      generate the pairs for a cells file (JSON list) and write one npz per task and run.json
  analyze  per-pair outcomes, per-cell summaries, plots and a receipt
"""

